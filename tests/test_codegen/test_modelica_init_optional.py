"""Tests for Modelica .mos init export of holdup / efficiency (holdup/efficiency extension).

These tests do not need the solver: a ColumnResult is constructed directly
with synthetic profiles.
"""

from __future__ import annotations

import re

import numpy as np
import pytest

pytest.importorskip("casadi")  # h2iso.mesh imports the CasADi solver package

from h2iso.codegen.modelica_init import generate_init_script
from h2iso.mesh.column import ColumnResult
from h2iso.species import SPECIES_ORDER

N = 8
NC = 6


def _make_result(
    with_holdup: bool = False, with_murphree: bool = False
) -> ColumnResult:
    rng = np.random.default_rng(42)
    x = rng.random((N, NC))
    x /= x.sum(axis=1, keepdims=True)
    y = rng.random((N, NC))
    y /= y.sum(axis=1, keepdims=True)
    result = ColumnResult(
        T_profile=np.linspace(23.0, 25.0, N),
        x_profile=x,
        y_profile=y,
        L_profile=np.full(N, 10.0),
        V_profile=np.full(N, 11.0),
        condenser_duty=-100.0,
        reboiler_duty=100.0,
        convergence_info={"status": "test"},
    )
    if with_holdup:
        result.holdup_l_profile = np.linspace(0.01, 0.02, N)
        result.holdup_v_profile = np.linspace(0.001, 0.002, N)
    if with_murphree:
        result.murphree_eff = np.full((N, NC), 0.85)
    return result


def _parse_vector(mos: str, name: str) -> np.ndarray:
    m = re.search(re.escape(name) + r'", "\{([^}]*)\}"\)', mos)
    assert m, f"{name} not found in .mos output"
    return np.array([float(v) for v in m.group(1).split(",")])


class TestCoreExports:
    def test_core_sections_present(self):
        mos = generate_init_script(_make_result(), "Pkg.Col")
        for name in ("T_init", "L_init", "V_init", "Q_cond", "Q_reb"):
            assert f"Pkg.Col.{name}" in mos
        for sp in ("H2", "HD", "HT", "D2", "DT", "T2"):
            assert f"Pkg.Col.x_{sp}_init" in mos
            assert f"Pkg.Col.y_{sp}_init" in mos

    def test_no_optional_lines_without_data(self):
        mos = generate_init_script(_make_result(), "Pkg.Col")
        assert "holdup_l_init" not in mos
        assert "holdup_v_init" not in mos
        assert "murphree_eff" not in mos

    def test_include_optional_false_suppresses(self):
        result = _make_result(with_holdup=True, with_murphree=True)
        mos = generate_init_script(result, "Pkg.Col", include_optional=False)
        assert "holdup_l_init" not in mos
        assert "murphree_eff" not in mos
        assert "Pkg.Col.T_init" in mos


class TestHoldupExport:
    def test_holdup_vectors_roundtrip(self):
        result = _make_result(with_holdup=True)
        mos = generate_init_script(result, "Pkg.Col")
        holdup_l = _parse_vector(mos, "Pkg.Col.holdup_l_init")
        holdup_v = _parse_vector(mos, "Pkg.Col.holdup_v_init")
        assert holdup_l.shape == (N,)
        assert holdup_v.shape == (N,)
        assert np.allclose(holdup_l, result.holdup_l_profile, rtol=1e-8)
        assert np.allclose(holdup_v, result.holdup_v_profile, rtol=1e-8)

    def test_only_liquid_emitted_when_vapor_missing(self):
        result = _make_result()
        result.holdup_l_profile = np.full(N, 0.5)
        mos = generate_init_script(result, "Pkg.Col")
        assert "holdup_l_init" in mos
        assert "holdup_v_init" not in mos


class TestMurphreeExport:
    def test_matrix_shape_and_values(self):
        result = _make_result(with_murphree=True)
        mos = generate_init_script(result, "Pkg.Col")
        m = re.search(r'murphree_eff", "(\{.*\})"\);', mos)
        assert m, "murphree_eff line not found"
        literal = m.group(1)
        rows = re.findall(r"\{([^{}]*)\}", literal)
        assert len(rows) == N
        for row in rows:
            values = [float(v) for v in row.split(",")]
            assert len(values) == NC
            assert all(abs(v - 0.85) < 1e-6 for v in values)

    def test_absent_without_spec(self):
        mos = generate_init_script(_make_result(), "Pkg.Col")
        assert "murphree_eff" not in mos


class TestLegacyFormatPreserved:
    """An earlier format-preservation decision: preserve the historical .mos format
    bit-for-bit and add the alternative (-overrideFile) alongside it.

    The legacy function below is a verbatim copy of
    ``generate_init_script`` as of the pristine snapshot (a historical
    working-copy commit).  The new function must produce
    byte-identical output for a result without holdup/efficiency data,
    so that any consumer of the old format is unaffected.
    """

    @staticmethod
    def _legacy_init_script(result, model_name):  # pragma: no cover - reference
        N = len(result.T_profile)
        lines = []
        lines.append(f"// Auto-generated by h2iso for model: {model_name}")
        lines.append(f"// N_stages = {N}")
        lines.append("")

        # Temperature profile
        T_str = ", ".join(f"{result.T_profile[j]:.6f}" for j in range(N))
        lines.append(f'setInitXml("{model_name}.T_init", "{{{T_str}}}");')
        lines.append("")

        # Liquid composition
        for i, sp in enumerate(SPECIES_ORDER):
            x_str = ", ".join(f"{result.x_profile[j, i]:.8g}" for j in range(N))
            lines.append(f'setInitXml("{model_name}.x_{sp}_init", "{{{x_str}}}");')
        lines.append("")

        # Vapor composition
        for i, sp in enumerate(SPECIES_ORDER):
            y_str = ", ".join(f"{result.y_profile[j, i]:.8g}" for j in range(N))
            lines.append(f'setInitXml("{model_name}.y_{sp}_init", "{{{y_str}}}");')
        lines.append("")

        # Flow profiles
        L_str = ", ".join(f"{result.L_profile[j]:.6f}" for j in range(N))
        V_str = ", ".join(f"{result.V_profile[j]:.6f}" for j in range(N))
        lines.append(f'setInitXml("{model_name}.L_init", "{{{L_str}}}");')
        lines.append(f'setInitXml("{model_name}.V_init", "{{{V_str}}}");')
        lines.append("")

        # Heat duties
        lines.append(
            f'setInitXml("{model_name}.Q_cond", "{result.condenser_duty:.4f}");'
        )
        lines.append(f'setInitXml("{model_name}.Q_reb", "{result.reboiler_duty:.4f}");')

        return "\n".join(lines) + "\n"

    def test_core_output_byte_identical_to_legacy(self):
        result = _make_result()  # no holdup, no efficiency
        legacy = self._legacy_init_script(result, "Pkg.Col")
        new = generate_init_script(result, "Pkg.Col")
        assert new == legacy

    def test_override_alternative_available_alongside(self):
        from h2iso.codegen.modelica_init import generate_override_file

        result = _make_result()
        override = generate_override_file(result, prefix="Col")
        # the alternative exists and carries the same core quantities
        assert "Col.T_init[1]=" in override
        assert "Col.Q_cond=" in override
